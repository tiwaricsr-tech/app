create extension if not exists pgcrypto;

-- ── roles / permissions ─────────────────────────────────────────────────────
create table if not exists roles (
  id          integer generated by default as identity primary key,
  name        text not null unique,
  label       text not null,
  description text,
  is_system   boolean not null default false,
  created_at  timestamptz not null default now()
);

create table if not exists permissions (
  id          integer generated by default as identity primary key,
  code        text not null unique,
  description text
);

create table if not exists role_permissions (
  role_id       integer not null references roles(id) on delete cascade,
  permission_id integer not null references permissions(id) on delete cascade,
  primary key (role_id, permission_id)
);

-- ── users ───────────────────────────────────────────────────────────────────
create table if not exists users (
  id            integer generated by default as identity primary key,
  full_name     text not null,
  email         text not null unique,
  password_hash text not null,             -- bcrypt, verified by the Node API
  phone         text,
  role_id       integer not null references roles(id),
  status        text not null default 'active' check (status in ('active','inactive')),
  last_login_at timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table if not exists categories (
  id          integer generated by default as identity primary key,
  name        text not null unique,
  description text,
  created_at  timestamptz not null default now()
);

create table if not exists products (
  id                  integer generated by default as identity primary key,
  name                text not null,
  sku                 text not null unique,
  category_id         integer references categories(id) on delete set null,
  image_url           text,
  description         text,
  purchase_price      numeric(12,2) not null default 0 check (purchase_price >= 0),
  selling_price       numeric(12,2) not null default 0 check (selling_price >= 0),
  low_stock_threshold integer not null default 10 check (low_stock_threshold >= 0),
  status              text not null default 'active' check (status in ('active','archived')),
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

-- One row per product. The CHECK is the last line of defence against negative stock.
create table if not exists inventory (
  id         integer generated by default as identity primary key,
  product_id integer not null unique references products(id) on delete cascade,
  quantity   integer not null default 0 check (quantity >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists stock_movements (
  id              integer generated by default as identity primary key,
  product_id      integer not null references products(id) on delete cascade,
  type            text not null check (type in ('in','out','sale','adjustment','sale_cancel','sale_refund','return')),
  quantity_change integer not null,
  quantity_before integer not null,
  quantity_after  integer not null check (quantity_after >= 0),
  unit_cost       numeric(12,2),
  reference_type  text,
  reference_id    integer,
  note            text,
  user_id         integer references users(id),
  created_at      timestamptz not null default now()
);

create table if not exists invoices (
  id               integer generated by default as identity primary key,
  invoice_no       text not null unique,
  customer_name    text not null,
  customer_phone   text,
  customer_email   text,
  customer_address text,
  status           text not null default 'paid' check (status in ('paid','cancelled','refunded')),
  subtotal         numeric(12,2) not null default 0,
  discount_type    text not null default 'percent' check (discount_type in ('percent','fixed')),
  discount_value   numeric(12,2) not null default 0,
  discount_amount  numeric(12,2) not null default 0,
  tax_rate         numeric(5,2) not null default 0,
  tax_amount       numeric(12,2) not null default 0,
  total            numeric(12,2) not null default 0,
  payment_method   text not null default 'cash',
  notes            text,
  created_by       integer references users(id),
  updated_by       integer references users(id),
  cancelled_by     integer references users(id),
  cancelled_reason text,
  cancelled_at     timestamptz,
  refunded_at      timestamptz,
  idempotency_key  text unique,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create table if not exists invoice_items (
  id           integer generated by default as identity primary key,
  invoice_id   integer not null references invoices(id) on delete cascade,
  product_id   integer not null references products(id),
  product_name text not null,
  sku          text not null,
  unit_price   numeric(12,2) not null,
  quantity     integer not null check (quantity > 0),
  line_total   numeric(12,2) not null
);

create table if not exists counters (
  name  text primary key,
  value integer not null default 0
);

create table if not exists activity_log (
  id         integer generated by default as identity primary key,
  user_id    integer references users(id),
  action     text not null,
  entity     text,
  entity_id  integer,
  detail     text,
  created_at timestamptz not null default now()
);

create index if not exists idx_products_category  on products(category_id);
create index if not exists idx_products_name      on products(name);
create index if not exists idx_movements_product  on stock_movements(product_id, created_at desc);
create index if not exists idx_movements_created  on stock_movements(created_at desc);
create index if not exists idx_invoices_created   on invoices(created_at desc);
create index if not exists idx_invoices_status    on invoices(status);
create index if not exists idx_invoice_items_inv  on invoice_items(invoice_id);
create index if not exists idx_invoice_items_prod on invoice_items(product_id);

-- ── Atomic stock primitives (usable from RPC / SQL client as well as the API) ──
create or replace function deduct_stock(p_product_id integer, p_qty integer)
returns table (quantity_before integer, quantity_after integer)
language plpgsql as $$
declare
  v_before integer;
  v_after  integer;
begin
  if p_qty is null or p_qty <= 0 then
    raise exception 'INVALID_QTY';
  end if;

  select quantity into v_before from inventory where product_id = p_product_id for update;
  if not found then
    raise exception 'PRODUCT_NOT_FOUND';
  end if;
  if v_before < p_qty then
    raise exception 'INSUFFICIENT_STOCK';
  end if;

  v_after := v_before - p_qty;
  update inventory set quantity = v_after, updated_at = now() where product_id = p_product_id;
  return query select v_before, v_after;
end $$;

create or replace function restore_stock(p_product_id integer, p_qty integer)
returns table (quantity_before integer, quantity_after integer)
language plpgsql as $$
declare
  v_before integer;
  v_after  integer;
begin
  select quantity into v_before from inventory where product_id = p_product_id for update;
  if not found then raise exception 'PRODUCT_NOT_FOUND'; end if;
  v_after := v_before + p_qty;
  update inventory set quantity = v_after, updated_at = now() where product_id = p_product_id;
  return query select v_before, v_after;
end $$;

