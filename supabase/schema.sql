select r.id, p.id
from roles r
join permissions p on (
     r.name = 'admin'
  or (r.name = 'manager' and p.code in (
        'products.view','products.create','products.update','products.delete','stock.adjust',
        'inventory.view','invoices.view','invoices.create','invoices.edit','invoices.cancel',
        'reports.view','categories.manage'))
  or (r.name = 'staff' and p.code in ('products.view','inventory.view','invoices.view','invoices.create'))
)
on conflict do nothing;

-- ─────────────────────────────────────────────────────────────────────────────
--  Identity sequence maintenance
--  Bulk imports supply explicit ids, which do not advance the identity
--  sequences; the next INSERT would then collide. Call this after loading data.
--  Exposed over the API as POST /rest/v1/rpc/reset_identity_sequences.
-- ─────────────────────────────────────────────────────────────────────────────
create or replace function reset_identity_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  t text;
begin
  foreach t in array array[
    'roles','permissions','users','categories','products','inventory',
    'stock_movements','invoices','invoice_items','activity_log'
  ] loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, %L), coalesce((select max(id) from %I), 1), (select count(*) > 0 from %I))',
      t, 'id', t, t
    );
  end loop;
end $$;

comment on function reset_identity_sequences() is
  'Realigns identity sequences with MAX(id). Run after any bulk import.';
